动员令在短短四个小时内传遍了茫茫冰原。三百万军民爆发出了令人难以置信的生存潜能。所有的身份标签在生存危机前被全部粉碎：工程师、拖拉机手、地质队员、退伍老兵、驯鹿牧民、医护人员，被迅速编组为十二个工程兵团。

零下四十二度的暴风雪中，八百台重型柴油钻机在八号井场周围整齐排开。柴油冻结了，工人们就用喷灯整夜烘烤油箱；金属管壁冻脆了，老技工就脱下棉袄裹在接口处。

图雅的部族立下了不朽的功勋。两万头耐寒的北极驯鹿组成了一条永不停歇的冰原雪橇运输动脉。在履带式卡车完全无法通行的极深积雪中，驯鹿拉着沉重的特种金刚石钻头、钻杆与电缆，日夜穿梭在雪原与井场之间。驯鹿在呼啸的白毛风中倒下，牧民们就用自己的肩膀拉起雪橇继续前进。

工程在第七十二小时遭遇了毁灭性的生死危机。

钻头在推进至地下九千四百米时，猝然撞击到了极其坚硬的超深辉绿岩侵入体。硬度超过摩氏八度的超高温岩层瞬间将六根特种合金钻杆扭成了麻花，主钻台的超高压水力离合器当场发生机械过载爆裂，炙热的高压油浆在零下四十度的空气中瞬间喷发燃烧！

钻台卡死，主电机烧毁，地下深处的温度传感器数值开始诡异下跌——这意味着井道深处正在发生岩浆冷凝塌陷！

如果四个小时内无法更换高硬度金刚石聚晶复合片钻头并恢复钻进，万米深井就会彻底自闭坍塌，前功尽弃！

“让我上！”军垦老技工齐大爷，带着四个年轻徒弟，把毛巾浸湿缠在口鼻上，身上绑着粗麻绳，直接冲进了冒着毒气与高压蒸汽的井口平台。在零下四十五度的狂风与井口数百度的灼热蒸汽夹击之下，人的皮肉只要碰上铁器就会瞬间被粘掉一层皮。

齐大爷的手掌被高温机油烫得焦黑，但他用管钳死死咬住变形的法兰盘，在徒弟的合力呐喊声中，硬生生用血肉之躯在极度恶劣的环境下完成了紧急旁路泄压！

紧接着，图雅带着十二架最精锐的驯鹿雪橇，冒着十二级特强白风暴，将从关内军械库调运来的八个特种破岩聚能穿甲弹头送抵了现场！

“注药！引爆！”

随着李烽一声令下，特制的高能聚能穿甲装药被缆绳送入万米地底。

轰——！！！

并非地表的震耳欲聋，而是一阵源自地核深处的沉闷轰鸣。整片冰原的大地如同一面巨大的战鼓般剧烈起伏，冰层裂开蛛网般的缝隙。下一秒，超深地热层终于被彻底贯穿！

被禁锢在地幔深处数亿年的超临界热核等离子热流，顺着万米垂直井道，以超音速狂暴上涌！

轰隆隆隆！！！

一道直径逾十二米、赤红如熔岩铸造的等离子地热等离子喷流，伴随着千万吨高压过热蒸汽，自八号井口轰然冲天而起！

那道耀眼夺目的赤红光柱，撕碎了漫天的暴风雪，如同一柄由纯粹热量构成的开天巨剑，直刺三千米高空的漆黑云层！方圆百里的夜空在一瞬间被照亮得如同正午！

温暖的气浪以井口为中心，呈环形向四周疯狂扩散。积雪在蒸发，坚冰在融化，空气中的白霜在一瞬间化作漫天纷飞的温润雨雾！

在暴风雪中坚守了整整七个昼夜的三百万军民，仰望着那道贯穿天地的赤红光柱，爆发出震动苍穹的欢呼与痛哭！他们成功了！人类用自己的工业巨手，在大地深处抠出了一轮人造的太阳！

