燕崇山按在枪套上的手，缓缓松开了。他闭上眼，长叹一声：“……军令我担着。双堡关的重机枪，绝不对准向大地夺命的勇士。关内所有军用柴油、特种钢材、炸药雷管，你们……全拉走吧！”

历史在这一刻发生了彻底的转向。

三百万濒临死亡的难民，不再是乞求施舍的流民，而是在死神面前完成战时集结的“行星改造工程兵团”！

